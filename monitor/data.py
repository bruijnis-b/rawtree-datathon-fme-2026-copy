def request_detail(t0: float, t1: float) -> pd.DataFrame:
    """One row per request whose feedback landed in [t0, t1).

    Columns: rid, ts, served_by, fallback_reason, latency_ms, clicked, purchased, revenue,
    click_slot, buy_slot, is_new_user, cold, device, page, region, n_views, model_version.
    """
    sql = f"""
WITH (SELECT groupArray(product_id::String) FROM shop.catalog_updates
      WHERE change::String = 'new_product') AS new_products
SELECT f.rid AS rid, toString(f.ts) AS ts, f.served_by AS served_by, f.fallback_reason AS fallback_reason,
       f.latency_ms AS latency_ms, f.clicked AS clicked, f.purchased AS purchased, f.revenue AS revenue,
       indexOf(f.shown, f.clicked) AS click_slot, indexOf(f.shown, f.purchased) AS buy_slot,
       r.is_new_user AS is_new_user, r.is_new_user OR r.views_new AS cold,
       r.device AS device, r.page AS page, r.region AS region, r.n_views AS n_views,
       s.model_version AS model_version
FROM (
    SELECT request_id::String AS rid, ts::DateTime64(3) AS ts, served_by::String AS served_by,
           fallback_reason::String AS fallback_reason, accurateCastOrNull(latency_ms, 'Float64') AS latency_ms,
           clicked::String AS clicked, purchased::String AS purchased,
           ifNull(accurateCastOrNull(revenue_eur, 'Float64'), 0) AS revenue,
           CAST(shown AS Array(String)) AS shown
    FROM {TEAM}.feedback
    WHERE ts::DateTime64(3) >= {_t(t0)} AND ts::DateTime64(3) < {_t(t1)} AND request_id::String != '__init__'
) AS f
LEFT JOIN (
    SELECT request_id::String AS rid, is_new_user::Bool AS is_new_user,
           arrayMap(x -> x.product_id::String, recent_views::Array(JSON)) AS views,
           hasAny(views, new_products) AS views_new, length(views) AS n_views,
           context.device::String AS device, context.page::String AS page, context.region::String AS region
    FROM shop.requests
    WHERE ts::DateTime64(3) >= {_t(t0 - 30)} AND ts::DateTime64(3) < {_t(t1)}
) AS r ON f.rid = r.rid
LEFT JOIN (
    SELECT request_id::String AS rid, any(model_version::String) AS model_version
    FROM {TEAM}.submissions
    WHERE request_id::String IN (
        SELECT request_id::String FROM {TEAM}.feedback
        WHERE ts::DateTime64(3) >= {_t(t0)} AND ts::DateTime64(3) < {_t(t1)})
    GROUP BY rid
) AS s ON f.rid = s.rid
ORDER BY f.ts
"""
    df = pd.DataFrame(query(sql, timeout=30))
    if df.empty:
        return df
    df["ts"] = _to_local(df["ts"])
    df["latency_ms"] = pd.to_numeric(df["latency_ms"], errors="coerce")
    df["revenue"] = pd.to_numeric(df["revenue"], errors="coerce").fillna(0.0)
    for col in ("is_new_user", "cold"):
        df[col] = df[col].astype(bool)
    df["team"] = df["served_by"].eq("team")
    df["bought"] = df["purchased"].ne("")
    df["click"] = df["clicked"].ne("")
    df["model_version"] = df["model_version"].replace("", pd.NA).fillna(
        df["served_by"].where(df["served_by"] != "team", "(unknown)"))
    labels = model_labels()
    df["model"] = df["model_version"].map(lambda v: labels.get(v, (v, ""))[0])
    df["settings"] = df["model_version"].map(lambda v: labels.get(v, (v, ""))[1])
    return df


MODEL_VERSIONS = Path(__file__).resolve().parent.parent / "recsys" / "model_versions.json"
_labels_cache: tuple[float, dict[str, tuple[str, str]]] = (0.0, {})


def model_labels() -> dict[str, tuple[str, str]]:
    """Public model ID -> (readable name, settings), from our private recsys/model_versions.json.

    Name: the policy chain plus the ID, e.g. 'discount_boost → trend_boost → category_pop (mba8242)'.
    Settings: the outer policy's own settings, e.g. 'boost=3.0, inject=0.5'. Re-read when the file changes.
    """
    global _labels_cache
    try:
        mtime = MODEL_VERSIONS.stat().st_mtime
    except OSError:
        return {}
    if mtime != _labels_cache[0]:
        def chain(internal: str, params: dict) -> str:
            name = internal.rsplit("-v", 1)[0]
            inner = params.get("inner")
            if isinstance(inner, dict):
                return f"{name} → {chain(inner['policy'], inner)}"
            return f"{name} → {params['base']}" if "base" in params else name

        labels = {}
        for e in json.loads(MODEL_VERSIONS.read_text(encoding="utf-8")):
            own = ", ".join(f"{k}={v}" for k, v in e["params"].items() if k not in ("inner", "base", "policy"))
            labels[e["public_id"]] = (f"{chain(e['internal'], e['params'])} ({e['public_id']})", own)
        _labels_cache = (mtime, labels)
    return _labels_cache[1]


# Score estimate. The leaderboard scores each component as 100 x (team - baseline) / (oracle - baseline),
# clipped to [0, 100], and does not publish the oracle. Fitting every team's published hourly scores on the
# practice day: score = (50 x conversion + 10 x cold) / 70 (reliability added nothing, the baseline being
# 100% on time), oracle conversion ~1.31 x the reference's in every hour, cold oracle ~10-15 (loosely
# determined; we use 6.5 x the reference's cold conversion). Error vs the published hourly scores: ~0.1-0.6.
ORACLE_PER_REFERENCE = 1.31
COLD_ORACLE_PER_REFERENCE = 6.5


def estimated_score(conv: float, cold: float, base: dict, ref: dict) -> float:
    """Leaderboard score (0-100) for these expected conversions, against the window's baseline and reference."""
    def part(team: float, b: float, oracle: float) -> float:
        return min(100.0, max(0.0, 100 * (team - b) / (oracle - b))) if oracle > b else 0.0
    return (50 * part(conv, base["conversion"], ORACLE_PER_REFERENCE * ref["conversion"])
            + 10 * part(cold, base["cold_conversion"], COLD_ORACLE_PER_REFERENCE * ref["cold_conversion"])) / 70


def official_by_model(t0: float, t1: float) -> pd.DataFrame:
    """Official (expected, no-luck) numbers per model_version of ours in [t0, t1], plus the estimated score.

    From the leaderboard's per-model view (any window of 15 min to 3 h). Columns: model_version,
    off_requests, off_conversion, off_cold, score_est.
    """
    t1 = min(t1, time.time())
    t0 = max(t0, t1 - 10800)
    if t1 - t0 < 900:
        t0 = t1 - 900
    state = leaderboard_state(by="model", **{"from": int(t0), "to": int(t1)})
    ours = next((t for t in state["teams"] if t["team_id"] == TEAM), None)
    if not ours or not state.get("baseline") or not state.get("reference"):
        return pd.DataFrame(columns=["model_version", "off_requests", "off_conversion", "off_cold", "score_est"])
    rows = [{"model_version": v["model_version"], "off_requests": v["requests"], "off_conversion": v["conversion"],
             "off_cold": v["cold_conversion"],
             "score_est": estimated_score(v["conversion"], v["cold_conversion"], state["baseline"], state["reference"])}
            for v in ours.get("versions", [])]
    return pd.DataFrame(rows)


def all_teams() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Every team on the public leaderboard, scored out of 100.

    Returns (board, hourly):
    - board: one row per team over the leaderboard's current window: team, score_est (our estimate of the
      score from its expected conversions, see estimated_score), last_hour_score and last_hour (the newest
      official hourly score), conversion, cold_conversion, on_time, requests, is_us.
    - hourly: the official hourly scores of every team: team, hour (UTC epoch), score.
    """
    state = leaderboard_state()
    base, ref = state.get("baseline"), state.get("reference")
    progress = state.get("progress") or {}
    hourly = pd.DataFrame([{"team": t, "hour": h, "score": v} for t, rows in progress.items() for h, v in rows],
                          columns=["team", "hour", "score"])
    rows = []
    for t in state.get("teams", []):
        last = (progress.get(t["team_id"]) or [[None, None]])[-1]
        rows.append({
            "team": t["team_id"],
            "score_est": estimated_score(t["conversion"], t["cold_conversion"], base, ref) if base and ref else None,
            "last_hour_score": last[1], "last_hour": last[0],
            "conversion": t["conversion"], "cold_conversion": t["cold_conversion"], "on_time": t["on_time"],
            "requests": t["requests"], "is_us": t["team_id"] == TEAM,
        })
    board = pd.DataFrame(rows)
    if not board.empty:
        board = board.sort_values("score_est", ascending=False, na_position="last").reset_index(drop=True)
        board.insert(0, "rank", range(1, len(board) + 1))
    return board, hourly


def summarize(df: pd.DataFrame) -> dict[str, float]:
    """Our own leaderboard row over a detail frame (realised outcomes, not the hidden probabilities)."""
    n = len(df)
    if n == 0:
        return {"requests": 0, "conversion": math.nan, "conversion_ci": math.nan, "cold_requests": 0,
                "cold_conversion": math.nan, "on_time": math.nan, "ctr": math.nan,
                "revenue_per_request": math.nan, "fallback_conversion": math.nan, "team_conversion": math.nan}
    p = df["bought"].mean()
    cold = df[df["cold"]]
    fb = df[~df["team"]]
    team = df[df["team"]]
    return {
        "requests": n,
        "conversion": 100 * p,
        "conversion_ci": 100 * 1.96 * math.sqrt(max(p * (1 - p), 1e-12) / n),
        "cold_requests": len(cold),
        "cold_conversion": 100 * cold["bought"].mean() if len(cold) else math.nan,
        "on_time": 100 * df["team"].mean(),
        "ctr": 100 * df["click"].mean(),
        "revenue_per_request": df["revenue"].mean(),
        "fallback_conversion": 100 * fb["bought"].mean() if len(fb) else math.nan,
        "team_conversion": 100 * team["bought"].mean() if len(team) else math.nan,
    }


