"""Data loading for the team monitor: SQL against RawTree, plus our own row of the public leaderboard.

All functions are plain Python (no Streamlit) so they can be reused by scripts and tests.
Window bounds are Unix epoch seconds (UTC) generated by our own code, never user text.
"""
from __future__ import annotations

import json
import math
import time
from pathlib import Path
from typing import Any

import pandas as pd

from monitor.rawtree import ROOT, TEAM, leaderboard_state, query

TZ = "Europe/Madrid"  # the event runs on Barcelona time (CET)
FINAL_START = 1794733200.0  # Sun 15 Nov 2026 10:00 CET (also published in /api/state)
FINAL_END = 1794740400.0  # Sun 15 Nov 2026 12:00 CET
SNAPSHOTS = ROOT / "data" / "official_snapshots.jsonl"


def _t(epoch: float) -> str:
    """SQL literal for an epoch-seconds bound."""
    return f"toDateTime64({float(epoch):.3f}, 3)"


def _to_local(series: pd.Series) -> pd.Series:
    return pd.to_datetime(series, utc=True).dt.tz_convert(TZ)


# --------------------------------------------------------------------------------------------
# Per-request detail: feedback + request context + our model_version
# --------------------------------------------------------------------------------------------

def request_detail(t0: float, t1: float) -> pd.DataFrame:
    """One row per request whose feedback landed in [t0, t1).

    Columns: rid, ts, served_by, fallback_reason, latency_ms, clicked, purchased, revenue,
    click_slot, buy_slot, is_new_user, cold, device, page, region, n_views, model_version.
    """
    sql = f"""
WITH (SELECT groupArray(product_id::String) FROM shop.catalog_updates
      WHERE change::String = 'new_product') AS new_products
SELECT f.rid AS rid, toString(f.ts) AS ts, f.served_by AS served_by, f.fallback_reason AS fallback_reason,
       f.latency_ms AS latency_ms, f.clicked AS clicked, f.purchased AS purchased, f.revenue AS revenue,
       indexOf(f.shown, f.clicked) AS click_slot, indexOf(f.shown, f.purchased) AS buy_slot,
       r.is_new_user AS is_new_user, r.is_new_user OR r.views_new AS cold,
       r.device AS device, r.page AS page, r.region AS region, r.n_views AS n_views,
       s.model_version AS model_version
FROM (
    SELECT request_id::String AS rid, ts::DateTime64(3) AS ts, served_by::String AS served_by,
           fallback_reason::String AS fallback_reason, accurateCastOrNull(latency_ms, 'Float64') AS latency_ms,
           clicked::String AS clicked, purchased::String AS purchased,
           ifNull(accurateCastOrNull(revenue_eur, 'Float64'), 0) AS revenue,
           CAST(shown AS Array(String)) AS shown
    FROM {TEAM}.feedback
    WHERE ts::DateTime64(3) >= {_t(t0)} AND ts::DateTime64(3) < {_t(t1)} AND request_id::String != '__init__'
) AS f
LEFT JOIN (
    SELECT request_id::String AS rid, is_new_user::Bool AS is_new_user,
           arrayMap(x -> x.product_id::String, recent_views::Array(JSON)) AS views,
           hasAny(views, new_products) AS views_new, length(views) AS n_views,
           context.device::String AS device, context.page::String AS page, context.region::String AS region
    FROM shop.requests
    WHERE ts::DateTime64(3) >= {_t(t0 - 30)} AND ts::DateTime64(3) < {_t(t1)}
) AS r ON f.rid = r.rid
LEFT JOIN (
    SELECT request_id::String AS rid, any(model_version::String) AS model_version
    FROM {TEAM}.submissions
    WHERE request_id::String IN (
        SELECT request_id::String FROM {TEAM}.feedback
        WHERE ts::DateTime64(3) >= {_t(t0)} AND ts::DateTime64(3) < {_t(t1)})
    GROUP BY rid
) AS s ON f.rid = s.rid
ORDER BY f.ts
"""
    df = pd.DataFrame(query(sql, timeout=30))
    if df.empty:
        return df
    df["ts"] = _to_local(df["ts"])
    df["latency_ms"] = pd.to_numeric(df["latency_ms"], errors="coerce")
    df["revenue"] = pd.to_numeric(df["revenue"], errors="coerce").fillna(0.0)
    for col in ("is_new_user", "cold"):
        df[col] = df[col].astype(bool)
    df["team"] = df["served_by"].eq("team")
    df["bought"] = df["purchased"].ne("")
    df["click"] = df["clicked"].ne("")
    df["model_version"] = df["model_version"].replace("", pd.NA).fillna(
        df["served_by"].where(df["served_by"] != "team", "(unknown)"))
    return df


def summarize(df: pd.DataFrame) -> dict[str, float]:
    """Our own leaderboard row over a detail frame (realised outcomes, not the hidden probabilities)."""
    n = len(df)
    if n == 0:
        return {"requests": 0, "conversion": math.nan, "conversion_ci": math.nan, "cold_requests": 0,
                "cold_conversion": math.nan, "on_time": math.nan, "ctr": math.nan,
                "revenue_per_request": math.nan, "fallback_conversion": math.nan, "team_conversion": math.nan}
    p = df["bought"].mean()
    cold = df[df["cold"]]
    fb = df[~df["team"]]
    team = df[df["team"]]
    return {
        "requests": n,
        "conversion": 100 * p,
        "conversion_ci": 100 * 1.96 * math.sqrt(max(p * (1 - p), 1e-12) / n),
        "cold_requests": len(cold),
        "cold_conversion": 100 * cold["bought"].mean() if len(cold) else math.nan,
        "on_time": 100 * df["team"].mean(),
        "ctr": 100 * df["click"].mean(),
        "revenue_per_request": df["revenue"].mean(),
        "fallback_conversion": 100 * fb["bought"].mean() if len(fb) else math.nan,
        "team_conversion": 100 * team["bought"].mean() if len(team) else math.nan,
    }


