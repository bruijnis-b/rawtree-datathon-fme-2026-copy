def official_snapshot() -> dict[str, Any]:
    """Our team's row (plus the baseline/reference yardsticks) from the public leaderboard JSON."""
    state = leaderboard_state()
    ours = next((t for t in state.get("teams", []) if t.get("team_id") == TEAM), None)
    return {
        "fetched_at": time.time(),
        "mode": state.get("mode"),
        "updated_at": state.get("updated_at"),
        "window": state.get("window"),
        "final_start": state.get("final_start", FINAL_START),
        "final_end": state.get("final_end", FINAL_END),
        "ours": ours,
        "baseline": state.get("baseline"),
        "reference": state.get("reference"),
        "progress": (state.get("progress") or {}).get(TEAM, []),
    }


def record_snapshot(snap: dict[str, Any]) -> None:
    """Append a snapshot to data/official_snapshots.jsonl if its leaderboard update is new."""
    SNAPSHOTS.parent.mkdir(parents=True, exist_ok=True)
    last = load_snapshots(tail=1)
    if last and last[-1].get("updated_at") == snap.get("updated_at"):
        return
    with SNAPSHOTS.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(snap) + "\n")


def load_snapshots(tail: int | None = None) -> list[dict[str, Any]]:
    if not SNAPSHOTS.exists():
        return []
    lines = SNAPSHOTS.read_text(encoding="utf-8").splitlines()
    if tail:
        lines = lines[-tail:]
    out = []
    for line in lines:
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out


def snapshot_history() -> pd.DataFrame:
    """Our official row over time, one line per leaderboard update we recorded."""
    rows = []
    for s in load_snapshots():
        ours = s.get("ours") or {}
        if not ours:
            continue
        rows.append({
            "updated": pd.Timestamp(s["updated_at"], unit="s", tz="UTC").tz_convert(TZ),
            "mode": s.get("mode"),
            "conversion": ours.get("conversion"),
            "cold_conversion": ours.get("cold_conversion"),
            "on_time": ours.get("on_time"),
            "revenue_per_request": ours.get("revenue_per_request"),
            "baseline_conversion": (s.get("baseline") or {}).get("conversion"),
            "reference_conversion": (s.get("reference") or {}).get("conversion"),
            "model_version": ours.get("model_version"),
        })
    return pd.DataFrame(rows)
