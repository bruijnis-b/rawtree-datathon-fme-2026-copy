def trending_subcategories(limit: int = 12) -> pd.DataFrame:
    """Views per subcategory, last 15 min vs the 3 hours before (starter query 3)."""
    df = pd.DataFrame(query(f"""
SELECT c.subcategory AS subcategory, c.category AS category,
       countIf(e.ts > now() - INTERVAL 15 MINUTE) AS views_15m,
       countIf(e.ts <= now() - INTERVAL 15 MINUTE) / 12 AS avg_per_15m_before,
       views_15m / greatest(avg_per_15m_before, 1) AS lift
FROM (SELECT product_id::String AS pid, ts::DateTime64(3) AS ts FROM shop.events
      WHERE event_type::String = 'view' AND ts::DateTime64(3) > now() - INTERVAL 195 MINUTE) AS e
INNER JOIN (SELECT product_id::String AS pid, subcategory::String AS subcategory, category::String AS category
            FROM shop.catalog) AS c ON c.pid = e.pid
GROUP BY subcategory, category
HAVING views_15m >= 20
ORDER BY lift DESC
LIMIT {int(limit)}
"""))
    return df


def events_per_minute(minutes: int = 60) -> pd.DataFrame:
    df = pd.DataFrame(query(f"""
SELECT toString(toStartOfMinute(ts::DateTime64(3))) AS minute, event_type::String AS event_type, count() AS events
FROM shop.events
WHERE ts::DateTime64(3) > now() - INTERVAL {int(minutes)} MINUTE
GROUP BY minute, event_type
ORDER BY minute
"""))
    if not df.empty:
        df["minute"] = _to_local(df["minute"])
    return df


CHANGE_TYPES = ["new_product", "price_change", "out_of_stock", "back_in_stock"]


def catalog_change_counts() -> dict[str, Any]:
    """Changes per type in the last hour and the hour before, plus products out of stock right now."""
    rows = query("""
SELECT change::String AS change,
       countIf(ts::DateTime64(3) > now() - INTERVAL 1 HOUR) AS last_hour,
       countIf(ts::DateTime64(3) <= now() - INTERVAL 1 HOUR) AS prev_hour
FROM shop.catalog_updates
WHERE ts::DateTime64(3) > now() - INTERVAL 2 HOUR
GROUP BY change
""")
    counts = {c: {"last_hour": 0, "prev_hour": 0} for c in CHANGE_TYPES}
    for r in rows:
        counts.setdefault(r["change"], {})
        counts[r["change"]] = {"last_hour": int(r["last_hour"]), "prev_hour": int(r["prev_hour"])}
    oos = query("""
SELECT count() AS n FROM (
    SELECT product_id::String AS pid
    FROM shop.catalog_updates
    WHERE change::String IN ('out_of_stock', 'back_in_stock')
    GROUP BY pid
    HAVING argMax(change::String, ts::DateTime64(3)) = 'out_of_stock')
""")
    return {"counts": counts, "out_of_stock_now": int(oos[0]["n"]) if oos else 0}


def catalog_changes(minutes: int = 60) -> pd.DataFrame:
    df = pd.DataFrame(query(f"""
SELECT toString(ts::DateTime64(3)) AS ts, change::String AS change, product_id::String AS product_id,
       category::String AS category, subcategory::String AS subcategory, brand::String AS brand,
       accurateCastOrNull(price_eur, 'Float64') AS price_eur
FROM shop.catalog_updates
WHERE ts::DateTime64(3) > now() - INTERVAL {int(minutes)} MINUTE
ORDER BY ts::DateTime64(3) DESC
LIMIT 500
"""))
    if not df.empty:
        df["ts"] = _to_local(df["ts"])
    return df


# --------------------------------------------------------------------------------------------
# Official numbers: our own row of the public leaderboard, kept locally for when it goes dark
# --------------------------------------------------------------------------------------------

def official_snapshot() -> dict[str, Any]:
    """Our team's row (plus the baseline/reference yardsticks) from the public leaderboard JSON."""
    state = leaderboard_state()
    ours = next((t for t in state.get("teams", []) if t.get("team_id") == TEAM), None)
    return {
        "fetched_at": time.time(),
        "mode": state.get("mode"),
        "updated_at": state.get("updated_at"),
        "window": state.get("window"),
        "final_start": state.get("final_start", FINAL_START),
        "final_end": state.get("final_end", FINAL_END),
        "ours": ours,
        "baseline": state.get("baseline"),
        "reference": state.get("reference"),
        "progress": (state.get("progress") or {}).get(TEAM, []),
    }


def record_snapshot(snap: dict[str, Any]) -> None:
    """Append a snapshot to data/official_snapshots.jsonl if its leaderboard update is new."""
    SNAPSHOTS.parent.mkdir(parents=True, exist_ok=True)
    last = load_snapshots(tail=1)
    if last and last[-1].get("updated_at") == snap.get("updated_at"):
        return
    with SNAPSHOTS.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(snap) + "\n")


def load_snapshots(tail: int | None = None) -> list[dict[str, Any]]:
    if not SNAPSHOTS.exists():
        return []
    lines = SNAPSHOTS.read_text(encoding="utf-8").splitlines()
    if tail:
        lines = lines[-tail:]
    out = []
    for line in lines:
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out


def snapshot_history() -> pd.DataFrame:
    """Our official row over time, one line per leaderboard update we recorded."""
    rows = []
    for s in load_snapshots():
        ours = s.get("ours") or {}
        if not ours:
            continue
        rows.append({
            "updated": pd.Timestamp(s["updated_at"], unit="s", tz="UTC").tz_convert(TZ),
            "mode": s.get("mode"),
            "conversion": ours.get("conversion"),
            "cold_conversion": ours.get("cold_conversion"),
            "on_time": ours.get("on_time"),
            "revenue_per_request": ours.get("revenue_per_request"),
            "baseline_conversion": (s.get("baseline") or {}).get("conversion"),
            "reference_conversion": (s.get("reference") or {}).get("conversion"),
            "model_version": ours.get("model_version"),
        })
    return pd.DataFrame(rows)
