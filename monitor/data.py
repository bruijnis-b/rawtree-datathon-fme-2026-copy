def heartbeat() -> dict[str, Any]:
    """Latest request in the stream and latest answer of ours that was served."""
    rows = query(f"""
SELECT
  (SELECT toUnixTimestamp64Milli(max(ts::DateTime64(3))) FROM shop.requests) AS last_request_ms,
  (SELECT toUnixTimestamp64Milli(max(ts::DateTime64(3))) FROM {TEAM}.feedback
     WHERE served_by::String = 'team') AS last_served_ms,
  (SELECT toUnixTimestamp64Milli(max(ts::DateTime64(3))) FROM {TEAM}.feedback
     WHERE request_id::String != '__init__') AS last_feedback_ms
""")
    row = rows[0] if rows else {}
    now = time.time()

    def age(key: str) -> float:
        v = row.get(key)
        return now - float(v) / 1000 if v not in (None, 0, "0") else math.nan

    return {"request_age_s": age("last_request_ms"), "served_age_s": age("last_served_ms"),
            "feedback_age_s": age("last_feedback_ms")}


def answering_now(oldest_s: int = 15, newest_s: int = 4) -> dict[str, Any]:
    """Fast liveness check that does not wait for feedback (which lands ~4 s after each request).

    Of the requests that arrived between `oldest_s` and `newest_s` seconds ago (old enough that an
    answer should exist), how many have a submission of ours? Reacts within ~5-10 s of a stop.
    """
    row = query(f"""
SELECT count() AS requests,
       countIf(request_id::String IN (SELECT request_id::String FROM {TEAM}.submissions)) AS answered
FROM shop.requests
WHERE ts::DateTime64(3) BETWEEN now() - INTERVAL {int(oldest_s)} SECOND AND now() - INTERVAL {int(newest_s)} SECOND
""", timeout=10)[0]
    n, a = int(row["requests"]), int(row["answered"])
    return {"requests": n, "answered": a, "share": 100 * a / n if n else math.nan}


